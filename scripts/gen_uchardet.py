#!/usr/bin/env python3
"""Generate src/uchardet_data.rs from the uchardet C++ sources bundled with cchardet 2.2.0a2.

Usage: gen_uchardet.py [<uchardet src dir> [<out file>]]

Without a source dir, the pinned cchardet sdist is downloaded from PyPI and checked by sha256.
The output defaults to src/uchardet_data.rs in this repo.
"""
import hashlib, io, pathlib, re, struct, sys, tarfile, tempfile, urllib.request

URL = "https://files.pythonhosted.org/packages/4c/c2/0e4364a4d6ce1a67f46bbce0731dee4d910ae1ee4467bd36ee68bd0cdd8b/cchardet-2.2.0a2.tar.gz"
SHA256 = "dd72bb1872eca9d279055bc7c3491a62ce1db7bfd330b7d48d7239a59c2f9823"
PREFIX = "cchardet-2.2.0a2/src/ext/uchardet/src/"


def fetch(dest: pathlib.Path) -> pathlib.Path:
    with urllib.request.urlopen(URL, timeout=60) as r:
        data = r.read()
    got = hashlib.sha256(data).hexdigest()
    if got != SHA256:
        sys.exit(f"{URL}: sha256 {got}, expected {SHA256}")
    with tarfile.open(fileobj=io.BytesIO(data)) as tf:
        members = [m for m in tf.getmembers() if m.name.startswith(PREFIX)]
        tf.extractall(dest, members=members, filter="data")
    return dest / PREFIX


args = sys.argv[1:]
if len(args) > 2:
    sys.exit(__doc__)
OUT = pathlib.Path(args[1]) if len(args) > 1 else pathlib.Path(__file__).resolve().parent.parent / "src/uchardet_data.rs"
if args:
    ROOT = pathlib.Path(args[0])
else:
    _tmp = tempfile.TemporaryDirectory()  # removed at exit
    ROOT = fetch(pathlib.Path(_tmp.name))


def strip_comments(s: str) -> str:
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)


def f32_literal(val_str: str) -> str:
    # Match C++ (float) literal rounding (IEEE-754 binary32 nearest-even).
    f = struct.unpack("<f", struct.pack("<f", float(val_str)))[0]
    return f"f32::from_bits(0x{struct.unpack('<I', struct.pack('<f', f))[0]:08X})"


def parse_pck4_array(src: str, name: str) -> list[int]:
    m = re.search(rf"\b{name}\s*\[[^\]]*\]\s*=\s*\{{(.*?)\}};", src, re.S)
    assert m, name
    consts = {"eStart": 0, "eError": 1, "eItsMe": 2}
    out = []
    for call in re.finditer(r"PCK4BITS\(([^)]+)\)", m.group(1)):
        vals = [x.strip() for x in call.group(1).split(",")]
        assert len(vals) == 8, vals
        out.extend(consts[v] if v in consts else int(v) for v in vals)
    return out


def parse_int_array(src: str, name: str) -> list[int]:
    m = re.search(rf"\b{name}\s*(?:\[[^\]]*\])+\s*=\s*\{{(.*?)\}};", src, re.S)
    assert m, name
    consts = {
        "ILL": 255, "CTR": 254, "SYM": 253, "RET": 252, "NUM": 251,
        "UDF": 0, "OTH": 1, "ASC": 2, "ASS": 3, "ACV": 4, "ACO": 5, "ASV": 6, "ASO": 7,
    }
    tokens = re.findall(r"[A-Za-z0-9_+-]+", m.group(1))
    return [consts[t] if t in consts else int(t) for t in tokens]


out = [
    "// Generated by scripts/gen_uchardet.py from uchardet in cchardet 2.2.0a2. Do not edit.",
    "",
    "pub struct SmModel {",
    "    pub class_table: &'static [u8; 256],",
    "    pub class_factor: usize,",
    "    pub state_table: &'static [u8],",
    "    pub char_len_table: &'static [u8],",
    "    pub name: &'static str,",
    "}",
    "",
    "pub struct SequenceModel {",
    "    pub char_to_order_map: &'static [u8; 256],",
    "    pub precedence_matrix: &'static [u8],",
    "    pub freq_char_count: u8,",
    "    pub typical_positive_ratio: f32,",
    "    pub charset_name: &'static str,",
    "}",
    "",
]

# 1. State machines (nsMBCSSM.cpp + nsEscSM.cpp)
sm_src = strip_comments((ROOT / "nsMBCSSM.cpp").read_text() + "\n" + (ROOT / "nsEscSM.cpp").read_text())
for m in re.finditer(
    r"SMModel\s+(?:const\s+)?(\w+)\s*=\s*\{\s*\{[^}]*,\s*(\w+)\s*\}\s*,\s*(\d+)\s*,\s*\{[^}]*,\s*(\w+)\s*\}\s*,\s*(\w+)\s*,\s*\"([^\"]+)\"",
    sm_src,
):
    model_name, cls_name, factor, st_name, len_name, charset = m.groups()
    cls_arr = parse_pck4_array(sm_src, cls_name)
    assert len(cls_arr) == 256, (model_name, len(cls_arr))
    st_arr = parse_pck4_array(sm_src, st_name)
    len_arr = parse_int_array(sm_src, len_name)
    rust_name = model_name.upper()
    out.append(f"pub static {rust_name}: SmModel = SmModel {{")
    out.append(f"    class_table: &[{', '.join(map(str, cls_arr))}],")
    out.append(f"    class_factor: {factor},")
    out.append(f"    state_table: &[{', '.join(map(str, st_arr))}],")
    out.append(f"    char_len_table: &[{', '.join(map(str, len_arr))}],")
    out.append(f'    name: "{charset}",')
    out.append("};\n")

# 2. CJK frequency tables (*.tab)
for tab_name, prefix in [
    ("Big5Freq.tab", "BIG5"),
    ("EUCKRFreq.tab", "EUCKR"),
    ("EUCTWFreq.tab", "EUCTW"),
    ("GB2312Freq.tab", "GB2312"),
    ("JISFreq.tab", "JIS"),
]:
    tab_src = strip_comments((ROOT / tab_name).read_text())
    ratio = re.search(rf"#define\s+{prefix}_TYPICAL_DISTRIBUTION_RATIO\s+\(float\)\s*([0-9.]+)", tab_src).group(1)
    size = int(re.search(rf"#define\s+{prefix}_TABLE_SIZE\s+(\d+)", tab_src).group(1))
    arr_name = re.search(r"static\s+const\s+PRInt16\s+(\w+)\s*\[", tab_src).group(1)
    vals = parse_int_array(tab_src, arr_name)
    assert len(vals) == size, (tab_name, len(vals), size)
    out.append(f"pub const {prefix}_TYPICAL_DISTRIBUTION_RATIO: f32 = {f32_literal(ratio)};")
    out.append(f"pub static {prefix}_CHAR_TO_FREQ_ORDER: [i16; {size}] = [")
    for i in range(0, size, 16):
        out.append("    " + ", ".join(map(str, vals[i : i + 16])) + ",")
    out.append("];\n")

# 3. Japanese context table (JpCntx.cpp)
jp_src = strip_comments((ROOT / "JpCntx.cpp").read_text())
jp_vals = parse_int_array(jp_src, "jp2CharContext")
assert len(jp_vals) == 83 * 83
out.append("pub static JP2_CHAR_CONTEXT: [[u8; 83]; 83] = [")
for i in range(0, 83 * 83, 83):
    out.append(f"    [{', '.join(map(str, jp_vals[i : i + 83]))}],")
out.append("];\n")

# 4. Latin1 tables (nsLatin1Prober.cpp)
lat_src = strip_comments((ROOT / "nsLatin1Prober.cpp").read_text())
lat_cls = parse_int_array(lat_src, "Latin1_CharToClass")
lat_mod = parse_int_array(lat_src, "Latin1ClassModel")
assert len(lat_cls) == 256 and len(lat_mod) == 64
out.append(f"pub static LATIN1_CHAR_TO_CLASS: [u8; 256] = [{', '.join(map(str, lat_cls))}];")
out.append(f"pub static LATIN1_CLASS_MODEL: [u8; 64] = [{', '.join(map(str, lat_mod))}];\n")

# 5. SBCS Language Models (LangModels/*.cpp + nsSBCSGroupProber.cpp)
models = {}
emitted_arrays = set()
for lang_file in sorted((ROOT / "LangModels").glob("*.cpp")):
    lang_tag = lang_file.stem.upper()
    lsrc = strip_comments(lang_file.read_text())
    for m in re.finditer(
        r"const\s+SequenceModel\s+(\w+)\s*=\s*\{\s*(\w+)\s*,\s*(\w+)\s*,\s*(\d+)\s*,\s*\(float\)\s*([0-9.]+)\s*,\s*\w+\s*,\s*\"([^\"]+)\"\s*\};",
        lsrc,
    ):
        mname, cmap_name, pmat_name, fcount, ratio, cs_name = m.groups()
        rcmap = f"{lang_tag}_{cmap_name.upper()}"
        rpmat = f"{lang_tag}_{pmat_name.upper()}"
        if rcmap not in emitted_arrays:
            cvals = parse_int_array(lsrc, cmap_name)
            assert len(cvals) == 256, (lang_file, cmap_name, len(cvals))
            out.append(f"static {rcmap}: [u8; 256] = [{', '.join(map(str, cvals))}];")
            emitted_arrays.add(rcmap)
        if rpmat not in emitted_arrays:
            pvals = parse_int_array(lsrc, pmat_name)
            fcount_i = int(fcount)
            assert len(pvals) == fcount_i * fcount_i, (lang_file, pmat_name, len(pvals), fcount_i)
            out.append(f"static {rpmat}: [u8; {len(pvals)}] = [")
            for i in range(0, len(pvals), 32):
                out.append("    " + ", ".join(map(str, pvals[i : i + 32])) + ",")
            out.append("];")
            emitted_arrays.add(rpmat)
        models[mname] = (rcmap, rpmat, int(fcount), f32_literal(ratio), cs_name)

for mname, (rcmap, rpmat, fcount, ratio, cs_name) in models.items():
    out.append(
        f"pub static {mname.upper()}: SequenceModel = SequenceModel {{ "
        f"char_to_order_map: &{rcmap}, precedence_matrix: &{rpmat}, "
        f'freq_char_count: {fcount}, typical_positive_ratio: {ratio}, charset_name: "{cs_name}" }};'
    )

sbcs_src = strip_comments((ROOT / "nsSBCSGroupProber.cpp").read_text())
prober_order = []
for idx in range(100):
    if idx == 10:
        continue
    m = re.search(rf"mProbers\[{idx}\]\s*=\s*new\s+nsSingleByteCharSetProber\(&(\w+)", sbcs_src)
    assert m, idx
    prober_order.append((idx, m.group(1)))

out.append("\npub static SBCS_MODELS_BEFORE_HEBREW: [&SequenceModel; 10] = [")
for idx, name in prober_order[:10]:
    assert idx < 10
    out.append(f"    &{name.upper()},")
out.append("];")

out.append("\npub static SBCS_MODELS_AFTER_HEBREW: [&SequenceModel; 87] = [")
for idx, name in prober_order[12:]:
    assert idx >= 13
    out.append(f"    &{name.upper()},")
out.append("];")

OUT.write_text("\n".join(out) + "\n")
